// 3. 去重
const allChars = [...new Set([...w100Chars, ...pinyinChars])];

// 4. 读字典，筛选
const fullDict = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/dict/word-full.json'), 'utf8'));
const dictMap = new Map(fullDict.map(x => [x.word, x]));

const g1Dict = {};
let hit = 0, miss = 0;
const missing = [];
for (const ch of allChars) {
  const d = dictMap.get(ch);
  if (d) {
    g1Dict[ch] = {
      p: d.pinyin,
      s: parseInt(d.strokes) || 0,
      r: d.radicals,
    };
    hit++;
  } else {
    missing.push(ch);
    miss++;
  }
}

fs.writeFileSync(
  path.join(ROOT, 'data/dict/word-g1.json'),
  JSON.stringify({ _meta: { source: 'pwxcoo/chinese-xinhua MIT', count: Object.keys(g1Dict).length, generated: new Date().toISOString() }, chars: g1Dict }, null, 2)
);
console.log(`✅ word-g1.json: ${hit} 命中, ${miss} 缺失`);
if (missing.length) console.log('  缺失:', missing.join(''));
